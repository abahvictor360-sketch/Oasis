#!/usr/bin/env python3
"""Apply the Oasis Orchard Technologies branding to the Linphone Android and iOS sources.

Usage:  python3 branding/rebrand.py [--android DIR] [--ios DIR]

Defaults to ./android and ./ios next to this script's parent directory. The
script is idempotent: run it on a pristine upstream snapshot after every
upstream update (see branding/update-upstream.sh), or run it again on an
already-rebranded tree with no effect. Settings live in branding/brand.json.

Requires: Python 3.9+, cairosvg (pip install cairosvg) for PNG rendering.
"""
import argparse
import json
import re
from pathlib import Path

import cairosvg

HERE = Path(__file__).resolve().parent
ASSETS = HERE / "assets"
CFG = json.loads((HERE / "brand.json").read_text())

APP = CFG["app_name"]
SITE_HOST = re.sub(r"^https?://", "", CFG["website"]).rstrip("/")

# Upstream user-facing links -> Oasis links. Ordered: longest/most specific first.
# SIP infrastructure (sip/subscribe/files/lime/stun.linphone.org) is NOT touched here;
# see BRANDING.md, section "SIP server".
URL_MAP = [
    ("https://www.linphone.org/en/terms-of-use/", CFG["terms_url"]),
    ("https://www.linphone.org/en/terms-of-use", CFG["terms_url"]),
    ("https://linphone.org/en/terms-of-use", CFG["terms_url"]),
    ("https://www.linphone.org/en/privacy-policy", CFG["privacy_policy_url"]),
    ("https://linphone.org/en/privacy-policy", CFG["privacy_policy_url"]),
    ("https://linphone.org/en/features/#security", CFG["services_url"]),
    ("https://linphone.org/linphone-softphone", CFG["services_url"]),
    ("https://linphone.org/en/docs/", CFG["support_url"]),
    ("https://linphone.org/docs/", CFG["support_url"]),
    ("https://linphone.org/contact", CFG["support_url"]),
    ("[linphone.org/contact]", "[%s/support]" % SITE_HOST),
    (">linphone.org/contact<", ">%s/support<" % SITE_HOST),
    ("linphone-android@belledonne-communications.com", CFG["support_email"]),
    ("linphone-iphone@belledonne-communications.com", CFG["support_email"]),
]

# Standalone word "Linphone" in user-visible text (not inside URLs, identifiers or file names).
APP_WORD = re.compile(r"(?<![\w/.:@-])Linphone(?![\w/@]|\.\w|-(?:android|iphone|sdk|desktop)\b)")

changed = []


def write_if_changed(path: Path, new: str, old: str):
    if new != old:
        path.write_text(new, encoding="utf-8")
        changed.append(str(path))


def edit(path: Path, fn):
    old = path.read_text(encoding="utf-8")
    write_if_changed(path, fn(old), old)


def map_urls(text: str) -> str:
    for a, b in URL_MAP:
        text = text.replace(a, b)
    return text


def render(svg: Path, out: Path, w: int, h: int = None, round_mask=False):
    data = svg.read_text()
    if round_mask:  # circular legacy launcher icon
        data = data.replace("<rect ", '<clipPath id="c"><circle cx="512" cy="512" r="512"/></clipPath><rect clip-path="url(#c)" ', 1)
        data = data.replace('<g transform="translate(512', '<g clip-path="url(#c)" transform="translate(512', 1)
    out.parent.mkdir(parents=True, exist_ok=True)
    cairosvg.svg2png(bytestring=data.encode(), write_to=str(out), output_width=w, output_height=h or w)
    changed.append(str(out))


def mark_paths():
    d = {}
    for line in (ASSETS / "mark.paths").read_text().splitlines():
        k, v = line.split("=", 1)
        d[k] = v
    return d


def android_vector(color: str, size_dp: int, inset_scale: float = 1.0) -> str:
    """Logo mark as an Android VectorDrawable (24x24 viewport)."""
    m = mark_paths()
    t = 12 * (1 - inset_scale)
    return f"""<?xml version="1.0" encoding="utf-8"?>
<!-- {CFG['company_name']} logo mark. Generated by branding/rebrand.py - edit branding/assets instead. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="{size_dp}dp"
    android:height="{size_dp}dp"
    android:viewportWidth="24"
    android:viewportHeight="24">
    <group android:translateX="{t:.3f}" android:translateY="{t:.3f}" android:scaleX="{inset_scale}" android:scaleY="{inset_scale}">
        <path
            android:pathData="{m['RING']}"
            android:strokeColor="{color}"
            android:strokeWidth="{m['RING_STROKE']}"
            android:strokeLineCap="round"
            android:fillColor="#00000000"/>
        <path
            android:pathData="{m['LEAF']}"
            android:fillColor="{color}"/>
        <group android:pivotX="12" android:pivotY="12" android:scaleX="0.58" android:scaleY="0.58">
            <path
                android:pathData="{m['PHONE']}"
                android:fillColor="{color}"/>
        </group>
    </group>
</vector>
"""


# --------------------------------------------------------------------------- Android
def rebrand_android(root: Path):
    app = root / "app"
    res = app / "src/main/res"

    # Application id (Kotlin namespace org.linphone is kept on purpose: it is not user-visible
    # and keeping it makes upstream merges trivial).
    def gradle(t):
        t = re.sub(r'val packageName = "[^"]+"', f'val packageName = "{CFG["android_application_id"]}"', t)
        t = t.replace('"linphone-android-${variant', f'"{CFG["android_apk_prefix"]}-${{variant')
        return t
    edit(app / "build.gradle.kts", gradle)

    # Upstream's Firebase project is bound to org.linphone; the build enables FCM only if the file exists.
    gs = app / "google-services.json"
    if gs.exists():
        gs.unlink()
        changed.append(f"{gs} (removed)")

    # App name (an XML entity in every translation) + links.
    for f in sorted(res.glob("values*/strings.xml")):
        edit(f, lambda t: APP_WORD.sub(APP, map_urls(re.sub(r'<!ENTITY appName "[^"]*">', f'<!ENTITY appName "{APP}">', t))))

    # Brand colors. Upstream's "orange_main" is the primary brand color used throughout the theme.
    def colors(t):
        t = re.sub(r'(<color name="orange_main_500">)[^<]+', r"\g<1>" + CFG["color_primary"], t)
        t = re.sub(r'(<color name="orange_main_100">)[^<]+', r"\g<1>" + CFG["color_primary_light"], t)
        return t
    for f in res.glob("values*/colors.xml"):
        edit(f, colors)

    # Logos
    (res / "drawable/welcome_linphone_logo.xml").write_text(android_vector(CFG["color_primary"], 100))
    (res / "drawable/linphone_splashscreen.xml").write_text(android_vector("@color/orange_main_500", 60, 0.5))
    (res / "drawable/linphone_notification.xml").write_text(android_vector("#FFFFFFFF", 24))
    render(ASSETS / "wordmark.svg", res / "drawable/linphone_splashscreen_branding.png", 1000, 400)

    # Launcher icons: adaptive (foreground over orange_main_500 = brand color) + legacy PNGs.
    for dpi, scale in {"mdpi": 1, "hdpi": 1.5, "xhdpi": 2, "xxhdpi": 3, "xxxhdpi": 4}.items():
        d = res / f"mipmap-{dpi}"
        render(ASSETS / "adaptive-foreground.svg", d / "linphone_launcher_icon_foreground.png", int(108 * scale))
        render(ASSETS / "app-icon.svg", d / "ic_launcher.png", int(48 * scale))
        render(ASSETS / "app-icon.svg", d / "ic_launcher_round.png", int(48 * scale), round_mask=True)

    # Play Store metadata icon, if present
    for f in root.glob("metadata/**/icon.png"):
        render(ASSETS / "app-icon.svg", f, 512)


# --------------------------------------------------------------------------- iOS
def rebrand_ios(root: Path):
    bid = CFG["ios_bundle_id"]

    def ids(t):
        t = t.replace("group.org.linphone.phone", f"group.{bid}")
        t = t.replace("org.linphone.phone", bid)
        t = t.replace("org.linphone.LinphoneApp", f"{bid}.LinphoneApp")
        return t

    # Xcode project: bundle ids, display name, signing team.
    def pbx(t):
        t = ids(t)
        t = re.sub(r"INFOPLIST_KEY_CFBundleDisplayName = Linphone;", f'INFOPLIST_KEY_CFBundleDisplayName = "{APP}";', t)
        t = t.replace("INFOPLIST_KEY_CFBundleDisplayName = linphoneExtension;", f'INFOPLIST_KEY_CFBundleDisplayName = "{APP}";')
        t = re.sub(r"DEVELOPMENT_TEAM = [^;]*;", f'DEVELOPMENT_TEAM = "{CFG["ios_development_team"]}";', t)
        return t
    edit(root / "LinphoneApp.xcodeproj/project.pbxproj", pbx)

    # App group / entitlements / Info.plist / Swift identifiers.
    # GoogleService-Info.plist is deliberately left alone: it must be replaced with your own Firebase file.
    for f in list(root.rglob("*.entitlements")) + list(root.rglob("Info.plist")) + [root / "Shared.xcconfig"]:
        edit(f, ids)

    # Swift: identifiers, user-visible URLs and the hardcoded app-name fallbacks.
    for f in root.rglob("*.swift"):
        def swift(t):
            t = map_urls(ids(t))
            t = t.replace('?? "Linphone"', f'?? "{APP}"')
            t = t.replace('content.title = "Linphone"', f'content.title = "{APP}"')
            return t
        edit(f, swift)

    # Localized strings: links + app name in values.
    line_re = re.compile(r'^(\s*"[^"]+"\s*=\s*")(.*)(";\s*)$')
    for f in root.rglob("*.strings"):
        def strings(t):
            out = []
            for line in t.split("\n"):
                m = line_re.match(line)
                if m:
                    line = m.group(1) + APP_WORD.sub(APP, map_urls(m.group(2))) + m.group(3)
                out.append(line)
            return "\n".join(out)
        edit(f, strings)
    for f in root.rglob("*.stringsdict"):
        edit(f, lambda t: APP_WORD.sub(APP, map_urls(t)))
    for f in root.rglob("AppIntentVocabulary.plist"):  # Siri example phrases
        edit(f, lambda t: APP_WORD.sub(APP, t))
    for f in root.rglob("*.xcstrings"):  # string catalogs (intents etc.)
        edit(f, lambda t: APP_WORD.sub(APP, map_urls(t)))

    # Theme color (the "orange" theme is upstream's default theme).
    def theme(t):
        return re.sub(
            r'(static let orange = Theme\(\s*name: "orange",\s*main100: Color\(hex: ")[^"]+("\),\s*main500: Color\(hex: ")[^"]+',
            r"\g<1>" + CFG["color_primary_light"] + r"\g<2>" + CFG["color_primary"], t)
    edit(root / "Linphone/Utils/ThemeManager.swift", theme)

    # Accent color
    r, g, b = (int(CFG["color_primary"][i:i + 2], 16) for i in (1, 3, 5))
    accent = {"colors": [{"idiom": "universal", "color": {"color-space": "srgb", "components": {
        "red": f"0x{r:02X}", "green": f"0x{g:02X}", "blue": f"0x{b:02X}", "alpha": "1.000"}}}],
        "info": {"author": "xcode", "version": 1}}
    p = root / "Linphone/Assets.xcassets/AccentColor.colorset/Contents.json"
    old = p.read_text()
    write_if_changed(p, json.dumps(accent, indent=2) + "\n", old)

    # Icons & logos
    xc = root / "Linphone/Assets.xcassets"
    render(ASSETS / "app-icon.svg", xc / "AppIcon.appiconset/1024x1024.png", 1024)
    logo = xc / "linphone.imageset/linphone.svg"
    old = logo.read_text()
    write_if_changed(logo, (ASSETS / "logo-mark.svg").read_text(), old)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--android", default=str(HERE.parent / "android"))
    ap.add_argument("--ios", default=str(HERE.parent / "ios"))
    a = ap.parse_args()
    if Path(a.android).is_dir():
        rebrand_android(Path(a.android))
    if Path(a.ios).is_dir():
        rebrand_ios(Path(a.ios))
    print(f"{len(changed)} files written")


if __name__ == "__main__":
    main()
